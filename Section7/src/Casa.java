
public class Casa {
    public int nrGeamuri;
    public int nrEtaje;
    public String culoare;

    // Create getter

    public int getNrGeamuri() {
        return nrGeamuri;
    }

    public int getNrEtaje() {
        return nrEtaje;
    }

    public String getCuloare() {
        return culoare;
    }

    // Create setter

    public void setNrGeamuri(int nrGeamuri) {
        this.nrGeamuri = nrGeamuri;
    }

    public void setNrEtaje(int nrEtaje) {
        this.nrEtaje = nrEtaje;
    }

    public void setCuloare(String culoare) {
        this.culoare = culoare;
    }



}
